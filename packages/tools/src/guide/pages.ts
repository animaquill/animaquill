/**
 * Pages of the manual that people write, in English: the types that operations of aq_edit share,
 * and short pages on how the editor does a kind of thing (its mechanisms and conventions, as facts:
 * not how a work should be made). The pages of operations are made from the registry and the table
 * of texts instead, see tools/guide.ts. A line of a page that starts with `[{"op":` is a batch of
 * aq_edit that runs on the sample project, packages/schema/fixtures/v1: the tests run each one.
 */

export interface ManualPage {
  readonly topic: string;
  /** Other topics that find the page: the names of the types it is also about. */
  readonly also?: readonly string[];
  /** What it is about, in the table of contents. */
  readonly title: string;
  readonly text: string;
}

const lines = (...parts: readonly string[]) => parts.join("\n");

